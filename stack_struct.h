/**
 * @file stack_struct.h
 * @brief Определение базовой структуры стека и статусов операций.
 */

#ifndef STACK_STRUCT_H
#define STACK_STRUCT_H

#include <stddef.h>

/**
 * @brief Статусы выполнения операций со стеком.
 * 
 * Используются для индикации успеха или ошибки при работе функций стека.
 */
typedef enum 
{
    STACK_OK    = 1,   ///< Операция выполнена успешно.
    STACK_ERROR = 0    ///< Произошла ошибка.
} StackStatus;

/**
 * @brief Структура, представляющая обобщённый стек.
 * 
 * Содержит указатели на данные, информацию о размере и ёмкости,
 * а также указатели на функции для работы со стеком (полиморфизм).
 */
typedef struct Stack 
{
    void*  data;          ///< Указатель на данные стека.
    size_t size;          ///< Текущее количество элементов в стеке.
    size_t capacity;      ///< Максимальная вместимость стека.
    size_t element_size;  ///< Размер одного элемента в байтах.

    /// Указатель на функцию-конструктор.
    struct Stack* (*ctr)(size_t, size_t);
    /// Указатель на функцию добавления элемента.
    int (*push)(struct Stack*, void*);
    /// Указатель на функцию получения верхнего элемента.
    int (*top )(struct Stack*, void*);
    /// Указатель на функцию удаления верхнего элемента.
    int (*pop )(struct Stack*);
    /// Указатель на функцию-деструктор.
    struct Stack* (*dtr)(struct Stack*);
} Stack;

#endif // STACK_STRUCT_H